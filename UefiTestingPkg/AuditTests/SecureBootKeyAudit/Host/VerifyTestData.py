ARRAY_PATTERN = re.compile(
    r"^CONST UINT8\s+(?P<name>\w+)\[\]\s*=\s*\{(?P<body>.*?)^\};",
    re.DOTALL | re.MULTILINE,
)
SIZE_PATTERN = re.compile(r"CONST UINTN\s+(?P<name>\w+)Size\s*=\s*(?P<size>\d+);")


class VerificationError(ValueError):
    """Raised when generated fixture evidence is invalid."""


def require(condition: bool, message: str) -> None:
    """Raise a fixture verification error when a condition is false."""
    if not condition:
        raise VerificationError(message)


def decode_exact(data: bytes, asn1_spec):
    """Decode exactly one DER value."""
    value, trailing = der_decode(data, asn1Spec=asn1_spec)
    require(not trailing, "DER value contains trailing data")
    return value


def parse_c_arrays(path: Path) -> dict[str, bytes]:
    """Parse generated byte arrays and declared sizes from TestData.c."""
    source = path.read_text(encoding="ascii")
    sizes = {
        match.group("name"): int(match.group("size"))
        for match in SIZE_PATTERN.finditer(source)
    }
    arrays = {}
    for match in ARRAY_PATTERN.finditer(source):
        name = match.group("name")
        require(name in sizes, f"{name} has no matching size declaration")
        body = "\n".join(
            line.split("//", 1)[0] for line in match.group("body").splitlines()
        )
        encoded = bytes(
            int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})", body)
        )
        size = sizes[name]
        require(
            size == len(encoded),
            f"{name} initializer and declared size differ",
        )
        arrays[name] = encoded

    require(arrays, "no generated C arrays were found")
    return arrays


def verify_manifest_artifacts(
    arrays: dict[str, bytes],
    manifest: dict[str, object],
    manifest_data: bytes,
) -> None:
    """Verify every manifest artifact and embedded fixture identity."""
    require(manifest["version"] == 6, "unsupported fixture manifest version")
    require(manifest["private_keys_emitted"] is False, "manifest emits private keys")
    require(
        manifest["roles"]["mldsa_pk_update_authority"]["public_key_sha256"]
        != manifest["roles"]["mldsa_image_signer"]["public_key_sha256"],
        "manifest reuses the ML-DSA key across authority and image-signer roles",
    )
    require(
        manifest["roles"]["ecdsa_pk_update_authority"]["public_key_sha256"]
        != manifest["roles"]["ecdsa_image_signer"]["public_key_sha256"],
        "manifest reuses the ECDSA key across authority and image-signer roles",
    )
    require(
        manifest["roles"]["ecdsa_pk_update_authority"]["certificate_artifact"]
        == "gSecureBootKeyAuditPkEcdsa",
        "manifest identifies the wrong ECDSA authority artifact",
    )
    require(
        manifest["roles"]["mldsa_pk_update_authority"]["certificate_artifact"]
        == "gSecureBootKeyAuditPkMldsa",
        "manifest identifies the wrong ML-DSA authority artifact",
    )
    require(
        manifest["roles"]["mldsa_image_signer"]["certificate_location"]
        == "gSecureBootKeyAuditHelloMldsa:authenticode",
        "manifest identifies the wrong image-signer location",
    )
    require(
        manifest["roles"]["rsa_image_signer"]["certificate_location"]
        == "gSecureBootKeyAuditHelloRsaMldsa:authenticode[0]",
        "manifest identifies the wrong RSA image-signer location",
    )
    require(
        manifest["roles"]["ecdsa_image_signer"]["certificate_location"]
        == "gSecureBootKeyAuditHelloRsaEcdsaMldsa:authenticode[1]",
        "manifest identifies the wrong ECDSA image-signer location",
    )

    for name, record in manifest["artifacts"].items():
        require(name in arrays, f"manifest artifact {name} is missing from TestData.c")
        data = arrays[name]
        require(len(data) == record["size"], f"{name} size does not match manifest")
        require(
            hashlib.sha256(data).hexdigest() == record["sha256"],
            f"{name} SHA-256 does not match manifest",
        )

    metadata_arrays = {
        "gSecureBootKeyAuditFixtureId",
        "gSecureBootKeyAuditManifestSha256",
    }
    require(
        set(arrays) - metadata_arrays == set(manifest["artifacts"]),
        "TestData.c and manifest artifact sets differ",
    )
    require(
        arrays["gSecureBootKeyAuditFixtureId"].decode("ascii")
        == manifest["fixture_id"],
        "embedded fixture ID does not match manifest",
    )
    require(
        arrays["gSecureBootKeyAuditManifestSha256"]
        == hashlib.sha256(manifest_data).digest(),
        "embedded manifest SHA-256 does not match manifest",
    )


def parse_esl_entries(
    data: bytes,
    expected_type: uuid.UUID,
) -> tuple[int, list[bytes]]:
    """Parse all entries from one EFI_SIGNATURE_LIST."""
    require(len(data) >= 28, "EFI_SIGNATURE_LIST is truncated")
    signature_type = uuid.UUID(bytes_le=data[:16])
    list_size, header_size, signature_size = struct.unpack_from("<III", data, 16)
    require(signature_type == expected_type, "EFI_SIGNATURE_LIST type is wrong")
    require(list_size == len(data), "EFI_SIGNATURE_LIST size is wrong")
    require(header_size == 0, "EFI_SIGNATURE_LIST header is not empty")
    require(signature_size > 0, "EFI_SIGNATURE_DATA size is zero")
    require(
        (len(data) - 28) % signature_size == 0,
        "EFI_SIGNATURE_LIST entries do not match signature size",
    )
    entries = [
        data[offset : offset + signature_size]
        for offset in range(28, len(data), signature_size)
    ]
    require(entries, "EFI_SIGNATURE_LIST has no entries")
    return signature_size, entries


def parse_esl(data: bytes, expected_type: uuid.UUID) -> tuple[int, bytes]:
    """Parse one single-entry EFI_SIGNATURE_LIST."""
    signature_size, entries = parse_esl_entries(data, expected_type)
    require(len(entries) == 1, "EFI_SIGNATURE_LIST does not contain one entry")
    return signature_size, entries[0]


def verify_self_signed_certificate(certificate: x509.Certificate) -> None:
    """Verify a generated self-signed certificate."""
    require(
        certificate.issuer == certificate.subject,
        "fixture certificate is not self-issued",
    )
    public_key = certificate.public_key()
    if isinstance(public_key, rsa.RSAPublicKey):
        require(public_key.key_size == 2048, "fixture RSA key is not 2048 bits")
        require(
            certificate.public_key_algorithm_oid.dotted_string == RSA_ENCRYPTION_OID,
            "fixture certificate SPKI algorithm is not RSA",
        )
        require(
            certificate.signature_algorithm_oid.dotted_string == SHA256_WITH_RSA_OID,
            "fixture RSA certificate signature is not SHA-256 with RSA",
        )
        public_key.verify(
            certificate.signature,
            certificate.tbs_certificate_bytes,
            padding.PKCS1v15(),
            certificate.signature_hash_algorithm,
        )
    elif isinstance(public_key, ec.EllipticCurvePublicKey):
        require(
            isinstance(public_key.curve, ec.SECP256R1),
            "fixture ECDSA key is not P-256",
        )
        require(
            certificate.public_key_algorithm_oid.dotted_string == EC_PUBLIC_KEY_OID,
            "fixture certificate SPKI algorithm is not EC",
        )
        require(
            certificate.signature_algorithm_oid.dotted_string == ECDSA_WITH_SHA256_OID,
            "fixture ECDSA certificate signature is not ECDSA with SHA-256",
        )
        public_key.verify(
            certificate.signature,
            certificate.tbs_certificate_bytes,
            ec.ECDSA(certificate.signature_hash_algorithm),
        )
    elif isinstance(public_key, mldsa.MLDSA87PublicKey):
        require(
            certificate.public_key_algorithm_oid.dotted_string == ML_DSA_87_OID,
            "fixture certificate SPKI algorithm is not ML-DSA-87",
        )
        require(
            certificate.signature_algorithm_oid.dotted_string == ML_DSA_87_OID,
            "fixture ML-DSA certificate signature is not ML-DSA-87",
        )
        public_key.verify(
            certificate.signature,
            certificate.tbs_certificate_bytes,
        )
    else:
        raise VerificationError("fixture certificate key profile is unsupported")


def parse_x509_esl(data: bytes, owner: uuid.UUID) -> x509.Certificate:
    """Extract and verify one X.509 certificate from an ESL."""
    signature_size, signature_data = parse_esl(data, EFI_CERT_X509_GUID)
    require(signature_size > 16, "X.509 EFI_SIGNATURE_DATA has no certificate")
    require(
        uuid.UUID(bytes_le=signature_data[:16]) == owner,
        "X.509 EFI_SIGNATURE_DATA owner is wrong",
    )
    certificate = x509.load_der_x509_certificate(signature_data[16:])
    verify_self_signed_certificate(certificate)
    return certificate


def certificate_identity(certificate: x509.Certificate) -> dict[str, str]:
    """Return stable certificate role evidence."""
    certificate_der = certificate.public_bytes(serialization.Encoding.DER)
    public_key_der = certificate.public_key().public_bytes(
        serialization.Encoding.DER,
        serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    return {
        "subject": certificate.subject.rfc4514_string(),
        "certificate_sha256": hashlib.sha256(certificate_der).hexdigest(),
        "public_key_sha256": hashlib.sha256(public_key_der).hexdigest(),
    }


def verify_role(
    certificate: x509.Certificate,
    expected: dict[str, str],
    role_name: str,
) -> None:
    """Verify manifest identity for one certificate role."""
    identity = certificate_identity(certificate)
    for field, value in identity.items():
        require(
            value == expected[field],
            f"{role_name} {field} does not match manifest",
        )


def parse_authentication_2(update: bytes) -> tuple[bytes, bytes, bytes]:
    """Split EFI_VARIABLE_AUTHENTICATION_2 into time, SignedData, and payload."""
    require(len(update) >= 40, "authenticated update is truncated")
    time = update[:16]
    (
        year,
        month,
        day,
        hour,
        minute,
        second,
        pad1,
        nanosecond,
        timezone,
        daylight,
        pad2,
    ) = struct.unpack("<HBBBBBBIhBB", time)
    require(
        year == 2026
        and month == 1
        and day == 1
        and hour == 0
        and minute <= 59
        and second <= 59
        and pad1 == 0
        and nanosecond == 0
        and timezone == 0
        and daylight == 0
        and pad2 == 0,
        "authenticated update EFI_TIME is invalid",
    )

    certificate_length, revision, certificate_type = struct.unpack_from(
        "<IHH", update, 16
    )
    require(certificate_length >= 24, "WIN_CERTIFICATE_UEFI_GUID is too short")
    require(
        16 + certificate_length <= len(update),
        "WIN_CERTIFICATE_UEFI_GUID exceeds update",
    )
    require(revision == 0x0200, "WIN_CERTIFICATE revision is wrong")
    require(certificate_type == 0x0EF1, "WIN_CERTIFICATE type is wrong")
    require(
        uuid.UUID(bytes_le=update[24:40]) == EFI_CERT_PKCS7_GUID,
        "WIN_CERTIFICATE GUID is not PKCS#7",
    )
    signed_data = update[40 : 16 + certificate_length]
    payload = update[16 + certificate_length :]
    return time, signed_data, payload


def signed_content(
    variable_name: str,
    variable_guid: uuid.UUID,
    time: bytes,
    payload: bytes,
) -> bytes:
    """Reconstruct the UEFI authenticated-variable bytes covered by CMS."""
    return (
        variable_name.encode("utf-16-le")
        + variable_guid.bytes_le
        + struct.pack("<I", SECURE_BOOT_KEY_ATTRIBUTES)
        + time
        + payload
    )


def wrap_signed_data(signed_data: bytes) -> bytes:
    """Wrap bare SignedData in ContentInfo for cryptography's parser."""
    content_info = rfc2315.ContentInfo()
    content_info["contentType"] = univ.ObjectIdentifier(CMS_SIGNED_DATA_OID)
    content_info["content"] = univ.Any(signed_data)
    return der_encode(content_info)


def signed_data_certificate(signed_data: bytes) -> x509.Certificate:
    """Extract the sole certificate from bare SignedData."""
    certificates = pkcs7.load_der_pkcs7_certificates(wrap_signed_data(signed_data))
    require(len(certificates) == 1, "SignedData does not contain one certificate")
    certificate = certificates[0]
    verify_self_signed_certificate(certificate)
    return certificate


def verify_rsa_signed_data(
    signed_data_der: bytes,
    content: bytes,
    expected_certificate: x509.Certificate,
) -> None:
    """Verify one detached RSA/SHA-256 PKCS#7 SignedData value."""
    signed_data = decode_exact(signed_data_der, rfc2315.SignedData())
    require(
        len(signed_data["signerInfos"]) == 1,
        "RSA SignedData signer count is wrong",
    )
    require(
        len(signed_data["digestAlgorithms"]) == 1
        and str(signed_data["digestAlgorithms"][0]["algorithm"]) == SHA256_OID,
        "RSA SignedData digest algorithm set is wrong",
    )
    require(
        str(signed_data["contentInfo"]["contentType"]) == CMS_DATA_OID
        and not signed_data["contentInfo"]["content"].hasValue(),
        "RSA SignedData is not detached data",
    )
    signer = signed_data["signerInfos"][0]
    require(
        str(signer["digestAlgorithm"]["algorithm"]) == SHA256_OID,
        "RSA SignedData digest algorithm is not SHA-256",
    )
    require(
        str(signer["digestEncryptionAlgorithm"]["algorithm"]) == RSA_ENCRYPTION_OID,
        "RSA SignedData signature algorithm is not rsaEncryption",
    )
    require(
        not signer["authenticatedAttributes"].hasValue(),
        "RSA SignedData unexpectedly contains signed attributes",
    )

    certificate = signed_data_certificate(signed_data_der)
    require(
        isinstance(certificate.public_key(), rsa.RSAPublicKey),
        "RSA SignedData signer does not use an RSA key",
    )
    require(
        certificate.public_bytes(serialization.Encoding.DER)
        == expected_certificate.public_bytes(serialization.Encoding.DER),
        "RSA SignedData contains the wrong signer certificate",
    )
    require(
        int(signer["issuerAndSerialNumber"]["serialNumber"])
        == certificate.serial_number,
        "RSA SignedData signer serial number is wrong",
    )
    require(
        der_encode(signer["issuerAndSerialNumber"]["issuer"])
        == certificate.issuer.public_bytes(),
        "RSA SignedData signer issuer is wrong",
    )
    certificate.public_key().verify(
        bytes(signer["encryptedDigest"]),
        content,
        padding.PKCS1v15(),
        hashes.SHA256(),
    )


